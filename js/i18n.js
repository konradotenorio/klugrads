/* Traduz uma string solta (usada em alert/confirm). */
function t(s){
  const d = I18N[state && state.lang];
  return (d && d[s]) || s;
}
/* Traduz o HTML já montado: conteúdo de texto entre tags e os atributos
   placeholder/aria-label/title. Só troca correspondências exatas, então o
   conteúdo do banco passa intacto. */
function translateHTML(html){
  const d = I18N[state && state.lang];
  if(!d) return html;
  // O HTML traz entidades (&gt;, &lt;, &amp;); as chaves do dicionário usam os
  // caracteres literais, então desescapa antes de procurar.
  const unesc = s => s.replace(/&gt;/g,'>').replace(/&lt;/g,'<').replace(/&amp;/g,'&');
  html = html.replace(/>([^<]+)</g, (m, txt)=>{
    const key = txt.trim();
    if(!key) return m;
    const tr = d[key] || d[unesc(key)];
    return tr ? m.replace(txt, txt.replace(key, tr)) : m;
  });
  html = html.replace(/(placeholder|aria-label|title)="([^"]+)"/g, (m, attr, val)=>{
    const k = val.trim();
    const tr = d[k] || d[unesc(k)];
    return tr ? `${attr}="${tr}"` : m;
  });
  return html;
}
